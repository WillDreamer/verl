"""
Placeholder dataset for environment-based training.
The actual data is generated by the environment during reset, not from files.
"""

import logging
from typing import Optional

import numpy as np
import torch
from omegaconf import DictConfig
from torch.utils.data import Dataset
from transformers import PreTrainedTokenizer, ProcessorMixin

logger = logging.getLogger(__name__)


class EnvPlaceholderDataset(Dataset):
    """
    A placeholder dataset for environment-based training.
    
    This dataset returns empty/placeholder data items. The actual prompts
    and observations are generated by the environment during reset().
    
    Args:
        size: Number of placeholder samples to generate
        tokenizer: Tokenizer (not used, but kept for compatibility)
        config: Configuration object
        processor: Processor (not used, but kept for compatibility)
    """

    def __init__(
        self,
        size: int,
        tokenizer: PreTrainedTokenizer,
        config: DictConfig,
        processor: Optional[ProcessorMixin] = None,
    ):
        self.size = size
        self.tokenizer = tokenizer
        self.processor = processor
        self.config = config
        
        logger.info(f"[EnvPlaceholderDataset] Created placeholder dataset with {size} samples")
        logger.info("[EnvPlaceholderDataset] Actual data will be generated by environment during reset()")

    def __len__(self) -> int:
        return self.size

    def __getitem__(self, idx: int) -> dict:
        """
        Return a placeholder data item.
        
        The actual prompt and data will be generated by the environment
        during the rollout process (env.reset()).
        """
        # Return minimal placeholder data
        # The actual prompt will come from env.reset()
        return {
            "raw_prompt": [{"role": "user", "content": ""}],  # Empty placeholder
            "data_source": "env_generated",  # Indicate this is from environment
        }

    def state_dict(self) -> dict:
        """Return state dict for checkpointing."""
        return {
            "size": self.size,
            "current_index": 0,  # Placeholder, not used in env mode
        }

    def load_state_dict(self, state_dict: dict):
        """Load state dict from checkpoint."""
        if "size" in state_dict:
            self.size = state_dict["size"]
        logger.info(f"[EnvPlaceholderDataset] Loaded state dict, size: {self.size}")

